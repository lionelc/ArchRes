"""Renders results/summary.json as markdown tables (results/tables.md). Numbers are copied by code, not by hand.

  python3 report.py"""
import json, math, os

HERE = os.path.dirname(os.path.abspath(__file__))
S = json.load(open(os.path.join(HERE, 'results', 'summary.json')))


def f(x, d=3):
    if x is None:
        return '–'
    if isinstance(x, bool):
        return 'yes' if x else 'no'
    if isinstance(x, (list, tuple)):
        return ', '.join(f(v, d) for v in x)
    if isinstance(x, float):
        return f'{x:+.{d}f}' if abs(x) < 10 else f'{x:.1f}'
    return str(x)


def ratio(g):
    return '–' if g is None else f'{math.exp(g):.2f}×'


L = []
P = L.append
P('# Pilot tables (generated by report.py from results/summary.json)\n')
P('Log ratios: g = median over rounds of log(mean Y block / mean R block); g > 0 means Y (the reimplementation) is slower.\n')

P('## RQ1: funnel\n')
P('| Pair | cells | bands (single-block A/A p95, by stratum) | matched null b_m | robust gaps | robust pseudo-gaps (A/A) | layout spread (max) | robust after layout | alt. estimator sign disagreements | instr. sign agrees / captured |')
P('|---|---|---|---|---|---|---|---|---|---|')
for pair in ('A', 'B', 'C'):
    if pair not in S:
        continue
    X, F = S[pair], S['funnel'][pair]
    det = F['deterministic_counterparts']
    P(f"| {pair} | {F['cells']} | {', '.join(f'{k}: {v:.3f}' for k, v in X['bands'].items())} | {X['matched_null_p95']:.3f} | {F['robust_gaps']} | "
      f"{F['robust_pseudo_gaps']} | {f(F['layout_spread_max'])} | {F['robust_after_layout']} | {len(F['alt_estimator_disagreements'])} | "
      f"{sum(d['sign_agrees'] for d in det)}/{len(det)} |")
P('')

for pair, title in (('A', 'Pair A: Turso 0.8.3 vs SQLite 3.50.4'), ('B', 'Pair B: uutils 0.12.0 vs GNU coreutils 9.12'), ('C', 'Pair C: rav1d HEAD vs dav1d HEAD')):
    if pair not in S:
        continue
    P(f'## Survey, {title}\n')
    P('| cell | state | R time (s) | g per seed | ratio (seed mean) | band | robust | robust pseudo-gap |')
    P('|---|---|---|---|---|---|---|---|')
    for x in S[pair]['survey']:
        gm = sum(x['g']) / len(x['g'])
        P(f"| {x['cell']} | {x['state']} | {', '.join(f'{v:.3f}' for v in x['R_s'])} | {f(x['g'])} | {ratio(gm)} | {f(x['band'])} | {f(x['robust'])} | {f(x['pseudo_gap_robust'])} |")
    P('')

P('## Registered claims\n')
P('```json')
P(json.dumps(S['claims'], indent=1, default=str))
P('```\n')

P('## RQ2: planted gaps (known truth)\n')
P('| Pair | arm | expected | measured effects (cell, seed) | detection rate (e > b_m) |')
P('|---|---|---|---|---|')
for pair in ('A', 'B', 'C'):
    pl = S.get(pair, {}).get('plants')
    if not pl:
        continue
    for arm in ('P2', 'P5', 'P15', 'Pnull', 'Psham', 'Ya'):
        rows = [r for r in pl['rows'] if r['arm'] == arm]
        eff = '; '.join('%s/%s: %+.3f' % (r['cell'], r['seed'], r['effect']) for r in rows)
        P(f"| {pair} | {arm} | {f(rows[0]['expected'])} | {eff} | {pl['detection_rate'][arm]:.2f} |")
P('')

P('## RQ1: layout spread (environment padding 0–3 KiB)\n')
P('| Pair | cell | effects of 1, 2, 3 KiB | spread | band |')
P('|---|---|---|---|---|')
for pair in ('A', 'B', 'C'):
    for x in S.get(pair, {}).get('layout', []):
        P(f"| {pair} | {x['cell']} | {f(x['effects'])} | {x['spread']:.3f} | {x['band']:.3f} |")
P('')

P('## RQ4: natural witnesses (time split)\n')
P('| Pair | cell | g(Y0,R) per seed | U = g(Y1,R) per seed | band | robust Y0 gap | class |')
P('|---|---|---|---|---|---|---|')
for pair in ('A', 'B', 'C'):
    R = S.get('rq4', {}).get(pair)
    if not R:
        continue
    for c in R['cells']:
        P(f"| {pair} | {c['cell']} | {f(c['g_Y0_R'])} | {f(c['U_g_Y1_R'])} | {f(c['band'])} | {f(c['robust_Y0_gap'])} | {c['class'] or '–'} |")
    P(f"| {pair} | **total** | mass {R['Y0_gap_mass']} | | | {R['robust_Y0_gap_cells']} cells | decided share {R['share_of_Y0_gap_mass_decided']} |")
P('')

for key, title in (('timesplit', 'Time splits'), ('ko', 'Knock-outs'), ('swaps', 'Commit swaps (Pair C)')):
    for pair in ('A', 'B', 'C'):
        rows = S.get(pair, {}).get(key)
        if not rows:
            continue
        P(f'## {title}, Pair {pair}\n')
        groups = {}
        for r in rows:
            groups.setdefault(tuple(r.keys()), []).append(r)
        for cols, rs in groups.items():
            P('| ' + ' | '.join(cols) + ' |')
            P('|' + '---|' * len(cols))
            for r in rs:
                P('| ' + ' | '.join(f(r.get(c)) for c in cols) + ' |')
            P('')

P('## RQ3: correlational gap graph against counterfactual measurement\n')
P('```json')
P(json.dumps(S['cg'], indent=1, default=str))
P('```\n')

PC = S.get('planted_classes', {})
if PC:
    P('## RQ4: planted classes under the contract variant V_F (DEVIATIONS.md #8)\n')
    P(f"b = {PC['band']}, b_m = {PC['b_m']}. L_delta = log w - log T_R(upper); U = g(Yd, R), the switch-off witness under the main contract.\n")
    P('| cell | arm | planted (ms) | w measured (ms) | T_R upper (ms) | g | L_delta | U | label under V_F | truth under V_F | label under main | truth under main | F mislabelled frozen (main) |')
    P('|---|---|---|---|---|---|---|---|---|---|---|---|---|')
    for r in PC['rows']:
        P(f"| {r['cell']} | {r['arm']} | {r['planted_ms']:.2f} | {r['w_measured_ms']:.2f} | {r['T_R_upper_ms']:.2f} | {r['g']:+.3f} | {r['L_delta']:+.3f} | {r['U_witness_main']:+.3f} | "
          f"{r['label_under_V_F']} | {r['truth_under_V_F']} | {r['label_under_main']} | {r['truth_under_main']} | {r['mislabelled_frozen_under_main']} |")
    P('')

WC = S.get('wasi_classes', {})
if WC:
    P('## RQ4: uutils under its wasm32-wasip1 contract (DEVIATIONS.md #10)\n')
    P('| cell | T_R (ms) | T_R upper (ms) | T_Yw (ms) | g WASI | g native | floor L (ms, Thm 1) | L_delta | L_delta (sequential) | class under W | class native | knock-out reflink=never on R | g WASI vs R without reflink |')
    P('|---|---|---|---|---|---|---|---|---|---|---|---|---|')
    for r in WC['rows']:
        P(f"| {r['cell']} | {r['T_R_ms']:.2f} | {r['T_R_upper_ms']:.2f} | {r['T_Yw_ms']:.1f} | {r['g_wasi']:+.3f} | {r['g_native']:+.3f} | {r['floor_L_ms']:.1f} | {r['L_delta']:+.3f} | "
          f"{r['L_delta_seq']:+.3f} | {r['class_under_W']} | {r['class_native']} | {f(r.get('knockout_reflink_never_on_R'))} | {f(r.get('g_wasi_vs_R_without_reflink'))} |")
    P('')

P('## Exploratory and post hoc analyses (DEVIATIONS.md #6, #7)\n')
P('```json')
P(json.dumps(S.get('posthoc', {}), indent=1, default=str))
P('```\n')

open(os.path.join(HERE, 'results', 'tables.md'), 'w').write('\n'.join(L))
print('\n'.join(L))
